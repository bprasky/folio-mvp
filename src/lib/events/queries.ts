export async function getFestivalEvents() {
  try {
    // Get festivals from existing fetchFestivals function
    const festivals = await fetchFestivals();
    
    // Transform to the expected format for FestivalsCarousel
    const transformed = festivals.map(festival => ({
      id: festival.id,
      title: festival.title,
      location: festival.location,
      startDate: festival.startDate instanceof Date ? festival.startDate : new Date(festival.startDate),
      endDate: festival.endDate instanceof Date ? festival.endDate : new Date(festival.endDate),
      imageUrl: festival.imageUrl || "/images/event-placeholder.jpg",
      slug: festival.id, // Will be generated by FestivalCarousel server component if needed
    }));
    
    return transformed;
  } catch (error) {
    console.error('[getFestivalEvents] Error fetching festival events:', error);
    return [];
  }
}

export async function getLocalEvents({ city, radius }: { city: string; radius: number }) {
  const today = new Date();
  const start = subDays(today, 7);
  const end = addDays(today, 60);

  try {
    // Simple city name matching - no coordinate-based queries
    // Fixed: Filter by startDate instead of endDate, and include isApproved filter
    const rows = await prisma.$queryRawUnsafe(`
      SELECT e.*,
             COALESCE(e."city", f."city") as effective_city
      FROM "events" e
      LEFT JOIN "events" f ON f."id" = e."parentFestivalId"
      WHERE e."isPublic" = true
        AND e."isApproved" = true
        AND e."startDate" >= $1
        AND e."startDate" <= $2
        AND COALESCE(e."city", f."city") IS NOT NULL
        AND (
          LOWER(COALESCE(e."city", f."city")) = LOWER($3)
          OR LOWER(COALESCE(e."city", f."city")) LIKE LOWER($4)
        )
      ORDER BY e."startDate" ASC
    `, start, end, city.trim(), `%${city.trim()}%`) as any[];

    // Transform events to match FlowMosaic format
    return rows.map(event => ({
      id: event.id,
      title: event.title,
      imageUrl: event.imageUrl,
      heroImageUrl: event.imageUrl,
      coverImageUrl: event.imageUrl,
      rsvpCount: 0, // Will need to be fetched separately or included in the query
      viewCount: 0, // Not available in current data structure
      isSponsored: event.isSponsored || false,
      eventTypes: event.eventTypes || [],
      startsAt: event.startDate instanceof Date ? event.startDate.toISOString() : event.startDate,
      startDate: event.startDate instanceof Date ? event.startDate.toISOString() : event.startDate,
      href: `/events/preview/${event.id}`, // Use modal route
    }));

  } catch (error) {
    console.error('Error fetching local events:', error);
    return [];
  }
}
