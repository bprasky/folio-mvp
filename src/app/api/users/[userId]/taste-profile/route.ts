export const dynamic = 'force-dynamic';

import { NextRequest, NextResponse } from 'next/server';
import { getServerSession } from 'next-auth';
import { authOptions } from '@/lib/auth';
import { prisma } from '@/lib/prisma';
import { getConfirmedTastes } from '@/lib/intelligence/patterns';
import type { TasteProfileSummary, DesignerMatch } from '@/lib/intelligence/types';

/**
 * GET /api/users/[userId]/taste-profile
 *
 * Get user's taste profile summary
 */
export async function GET(
  request: NextRequest,
  context: { params: Promise<{ userId: string }> }
) {
  try {
    const { userId } = await context.params;
    const session = await getServerSession(authOptions);

    // Users can only view their own taste profile
    if (!session?.user?.id || session.user.id !== userId) {
      return NextResponse.json(
        { error: 'Unauthorized' },
        { status: 403 }
      );
    }

    // Get or create taste profile
    const profile = await prisma.userTasteProfile.upsert({
      where: { userId },
      create: { userId },
      update: {},
    });

    // Get confirmed and unconfirmed tastes
    const tastes = await getConfirmedTastes(userId);

    // Get user's boards
    const boards = await prisma.board.findMany({
      where: { userId },
      select: {
        id: true,
        name: true,
        type: true,
        roomType: true,
        autoGenerated: true,
        coverImageUrl: true,
        _count: {
          select: { saves: true },
        },
      },
      orderBy: { updatedAt: 'desc' },
    });

    // Get designer matches (placeholder - will implement full matching later)
    const designerMatches: DesignerMatch[] = [];

    const summary: TasteProfileSummary = {
      userId,
      styleName: profile.styleName,
      styleDescription: profile.styleDescription,
      confirmedAttributes: profile.confirmedAttributes,
      totalLikes: profile.totalLikes,
      totalSaves: profile.totalSaves,
      profileStrength: profile.profileStrength,
      topInferences: [
        ...tastes.confirmed.slice(0, 5),
        ...tastes.unconfirmed.slice(0, 3),
      ],
      designerMatches,
    };

    return NextResponse.json({
      profile: summary,
      boards: boards.map(b => ({
        id: b.id,
        name: b.name,
        type: b.type,
        roomType: b.roomType,
        autoGenerated: b.autoGenerated,
        coverImageUrl: b.coverImageUrl,
        saveCount: b._count.saves,
      })),
      tastes: {
        confirmed: tastes.confirmed,
        unconfirmed: tastes.unconfirmed,
      },
    });
  } catch (error) {
    console.error('[GET /api/users/[userId]/taste-profile] Error:', error);
    return NextResponse.json(
      { error: 'Failed to get taste profile' },
      { status: 500 }
    );
  }
}
