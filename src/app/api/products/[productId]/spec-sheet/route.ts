export const dynamic = 'force-dynamic';

import { NextRequest, NextResponse } from 'next/server';
import { prisma } from '@/lib/prisma';
import PDFDocument from 'pdfkit';

/**
 * GET /api/products/[productId]/spec-sheet
 *
 * Generates a PDF spec sheet from available product data.
 * Works even with minimal data — notes what's missing.
 */
export async function GET(
  _request: NextRequest,
  { params }: { params: { productId: string } }
) {
  const productId = params.productId;

  const product = await prisma.product.findUnique({
    where: { id: productId },
    select: {
      name: true,
      brand: true,
      description: true,
      price: true,
      imageUrl: true,
      url: true,
      category: true,
      vendor: {
        select: { name: true, companyName: true, email: true },
      },
    },
  });

  if (!product) {
    return NextResponse.json({ error: 'Product not found' }, { status: 404 });
  }

  // Generate PDF
  const doc = new PDFDocument({
    size: 'LETTER',
    margins: { top: 60, bottom: 60, left: 60, right: 60 },
    info: {
      Title: `${product.name} — Spec Sheet`,
      Author: 'Folio',
    },
  });

  const chunks: Buffer[] = [];
  doc.on('data', (chunk: Buffer) => chunks.push(chunk));

  const pdfPromise = new Promise<Buffer>((resolve) => {
    doc.on('end', () => resolve(Buffer.concat(chunks)));
  });

  // --- Header ---
  doc.fontSize(10).fillColor('#999999').text('PRODUCT SPECIFICATION', { align: 'center' });
  doc.moveDown(0.5);
  doc.fontSize(24).fillColor('#1a1a1a').text(product.name, { align: 'center' });

  if (product.brand) {
    doc.fontSize(12).fillColor('#666666').text(product.brand, { align: 'center' });
  }

  doc.moveDown(1);

  // --- Divider ---
  doc.moveTo(60, doc.y).lineTo(552, doc.y).strokeColor('#e0d8cf').lineWidth(0.5).stroke();
  doc.moveDown(1);

  // --- Spec Fields ---
  const addField = (label: string, value: string | null | undefined) => {
    if (!value) return;
    doc.fontSize(9).fillColor('#999999').text(label.toUpperCase(), { continued: false });
    doc.fontSize(11).fillColor('#333333').text(value);
    doc.moveDown(0.6);
  };

  addField('Description', product.description);
  addField('Category', product.category);
  addField('Brand / Manufacturer', product.brand || product.vendor?.companyName || product.vendor?.name);

  if (product.price) {
    addField('Price', `$${product.price.toLocaleString()}`);
  }

  if (product.url) {
    addField('Product URL', product.url);
  }

  if (product.vendor?.email) {
    addField('Vendor Contact', product.vendor.email);
  }

  // --- Missing data note ---
  const missing: string[] = [];
  if (!product.description) missing.push('description');
  if (!product.price) missing.push('pricing');
  if (!product.imageUrl) missing.push('product image');
  if (!product.brand && !product.vendor) missing.push('vendor/brand');

  if (missing.length > 0) {
    doc.moveDown(1);
    doc.moveTo(60, doc.y).lineTo(552, doc.y).strokeColor('#e0d8cf').lineWidth(0.5).stroke();
    doc.moveDown(0.5);
    doc.fontSize(9).fillColor('#b8965e').text(
      `Some details are still being added: ${missing.join(', ')}. ` +
      'Visit folioad.com for the latest product information.',
      { align: 'center' }
    );
  }

  // --- Footer ---
  doc.moveDown(2);
  doc.moveTo(60, doc.y).lineTo(552, doc.y).strokeColor('#e0d8cf').lineWidth(0.5).stroke();
  doc.moveDown(0.5);
  doc.fontSize(8).fillColor('#aaaaaa').text(
    `Generated by Folio · ${new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' })}`,
    { align: 'center' }
  );

  doc.end();
  const pdfBuffer = await pdfPromise;

  const filename = `${product.name.replace(/[^a-zA-Z0-9 ]/g, '').replace(/\s+/g, '_')}_Spec_Sheet.pdf`;

  return new NextResponse(new Uint8Array(pdfBuffer), {
    status: 200,
    headers: {
      'Content-Type': 'application/pdf',
      'Content-Disposition': `inline; filename="${filename}"`,
      'Cache-Control': 'no-store',
    },
  });
}
