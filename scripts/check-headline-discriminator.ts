/**
 * The headline discriminator.
 *
 * Every other check on this surface is a rule check: does the headline break a
 * stated rule. None of them can answer the question that actually matters, which is
 * whether the output reads like a human editor wrote it. A headline can pass every
 * mechanical check, survive the editor's four kill criteria, and still be obviously
 * machine-made to anyone who reads magazines.
 *
 * So: mix generated headlines into a held-out set of human-written ones, ask a model
 * which is which, and report how often a generated headline is taken for a real one.
 * That number is the only measurement here that moves when the writing gets better
 * rather than when the rules get stricter.
 *
 * ── The corpus, and why it is not read from our own database ─────────────────
 *
 * The obvious corpus is our published headlines. It is the wrong one, and the reason
 * is worth writing down: in Folio a published headline IS a generated headline that a
 * designer accepted. Scoring generated-vs-published would measure whether a batch
 * looks like the batches designers have already picked from — it would be satisfied
 * completely by a generator that reproduced today's output, which is the thing being
 * replaced. The comparison has to be against writing from outside the system.
 *
 * The held-out set is therefore human-written headlines from real design magazines,
 * supplied by the operator in a corpus file. It cannot be generated, and it must not
 * be invented for the same reason a frame's exemplars must not be: an invented
 * corpus measures agreement with whoever invented it.
 *
 * Corpus file: docs/audits/headline-discriminator-corpus.json
 *   { "human": ["...", "..."] }        // >= 20 recommended, human-written, held out
 *
 * ── Casing is normalized before the judge sees anything ─────────────────────
 *
 * Both sets are lowercased. Dwell and Remodelista set headlines in Title Case;
 * Folio's house style is sentence case. Left alone, that is a perfect tell — the
 * judge would score "Title Case = human" and the rate would measure which
 * publication's typographic convention the generator imitates, not whether the
 * writing is any good.
 *
 * It is the same trap the naming ban was: a house convention masquerading as a
 * quality signal. Folio's own sentence-case rule is unchanged; it simply has no
 * business inside this measurement.
 *
 * ── Reading the number ───────────────────────────────────────────────────────
 *
 * Reported as the misidentification rate: of the generated headlines shown, the
 * share the judge called human. 0% means every generated line is obvious. 50% means
 * the judge cannot tell, which is the ceiling — above 50% the judge is anti-correlated
 * and the run should be repeated, not celebrated.
 *
 * No CI floor. One run is a sample, the judge is a model, and a floor set from a
 * single number would fail honest work. Record runs in docs/23 until there is enough
 * history to know the spread.
 *
 * Run: npx tsx scripts/check-headline-discriminator.ts --generated <file.json>
 *   where <file.json> is { "generated": ["...", "..."] }
 *
 * Requires ANTHROPIC_API_KEY. Reads no database.
 */

import { readFileSync, existsSync } from 'fs';
import Anthropic from '@anthropic-ai/sdk';
import { MODELS } from '../src/lib/ai/models';

const CORPUS = 'docs/audits/headline-discriminator-corpus.json';

const JUDGE_SYSTEM = `You are a design magazine reader with a good ear. You will be shown a numbered list of headlines from interior design features. Some were written by human editors at real magazines. Some were generated by a language model.

For each one, say which. Judge on the writing alone — whether it reports something a person went and found out, whether the sentence has the specificity and the restraint of edited copy, whether it sounds like it was assembled from a description of a house.

Do not assume a fixed proportion. The mix is unknown to you and may be uneven.

Every headline has been lowercased. Capitalisation carries no signal here — do not read anything into it.

Return ONLY a JSON array, one entry per headline, in order:
[{"i": <number>, "verdict": "human"|"machine"}]

No preamble, no commentary, no code fence.`;

/** Deterministic shuffle: a fixed seed, so two runs of one corpus are comparable. */
function shuffle<T>(items: T[], seed = 20260825): T[] {
  const out = [...items];
  let s = seed;
  for (let i = out.length - 1; i > 0; i--) {
    s = (s * 1103515245 + 12345) & 0x7fffffff;
    const j = s % (i + 1);
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

async function main() {
  const genFlag = process.argv.indexOf('--generated');
  const genPath = genFlag >= 0 ? process.argv[genFlag + 1] : '';

  if (!existsSync(CORPUS)) {
    console.error(`\nNo held-out corpus at ${CORPUS}.`);
    console.error('It must contain human-written headlines from real design magazines:');
    console.error('  { "human": ["...", "..."] }');
    console.error('This cannot be generated and must not be invented — see the note at');
    console.error('the top of this file for why our own published headlines are the wrong set.\n');
    process.exit(2);
  }
  if (!genPath || !existsSync(genPath)) {
    console.error('\nPass --generated <file.json> containing { "generated": [...] }.');
    console.error('Produce one by pressing New options on a project and copying the batch,');
    console.error('or from the `kickerAlternatives` stored on a ProjectPost.\n');
    process.exit(2);
  }
  if (!process.env.ANTHROPIC_API_KEY) {
    console.error('\nANTHROPIC_API_KEY is not set. The judge is a model call.\n');
    process.exit(2);
  }

  const human: string[] = JSON.parse(readFileSync(CORPUS, 'utf8')).human ?? [];
  const generated: string[] = JSON.parse(readFileSync(genPath, 'utf8')).generated ?? [];
  if (human.length < 5 || generated.length < 5) {
    console.error(`\nToo small to mean anything: ${human.length} human, ${generated.length} generated.\n`);
    process.exit(2);
  }
  // Between the floor and the recommendation the run is legal but noisy. Said
  // loudly, because a number quoted without this caveat reads as settled.
  if (human.length < 20) {
    console.warn(`\n  WARNING: only ${human.length} human headlines (20 recommended).`);
    console.warn('  A rate from this few is a sample, not a baseline. See the corpus file\'s');
    console.warn('  _humanSelection note for why the set is small and what to collect.\n');
  }

  // Lowercased for the judge; the original is kept for the report, so what is
  // printed back is the headline as published rather than as measured.
  const flatten = (s: string) => s.toLocaleLowerCase();
  const mixed = shuffle([
    ...human.map((text) => ({ text, judged: flatten(text), truth: 'human' as const })),
    ...generated.map((text) => ({ text, judged: flatten(text), truth: 'machine' as const })),
  ]);

  const anthropic = new Anthropic();
  const response = await anthropic.messages.create({
    model: MODELS.sonnet,
    thinking: { type: 'disabled' },
    max_tokens: 2000,
    system: JUDGE_SYSTEM,
    messages: [{
      role: 'user',
      content: `${mixed.map((m, i) => `${i}. ${m.judged}`).join('\n')}\n\nJudge all ${mixed.length}.`,
    }],
  });

  const text = (response.content ?? [])
    .filter((b: any) => b.type === 'text').map((b: any) => b.text).join('');
  const match = text.match(/\[[\s\S]*\]/);
  if (!match) {
    console.error('\nThe judge returned no JSON array. Not scoring a partial run.\n');
    process.exit(1);
  }

  const verdicts = new Map<number, string>();
  for (const entry of JSON.parse(match[0])) {
    if (typeof entry?.i === 'number' && typeof entry?.verdict === 'string') {
      verdicts.set(entry.i, entry.verdict);
    }
  }
  // A headline the judge skipped is not a headline it got wrong. An incomplete
  // pass is discarded rather than scored, the same posture judgeHeadlines takes.
  if (verdicts.size !== mixed.length) {
    console.error(`\nIncomplete: ${verdicts.size} verdicts for ${mixed.length} headlines. Not scoring.\n`);
    process.exit(1);
  }

  let genShown = 0, genCalledHuman = 0, humanShown = 0, humanCalledHuman = 0;
  const passed: string[] = [];
  for (const [i, m] of mixed.entries()) {
    const calledHuman = verdicts.get(i) === 'human';
    if (m.truth === 'machine') {
      genShown++;
      if (calledHuman) { genCalledHuman++; passed.push(m.text); }
    } else {
      humanShown++;
      if (calledHuman) humanCalledHuman++;
    }
  }

  const rate = (genCalledHuman / genShown) * 100;
  console.log(`\nHEADLINE DISCRIMINATOR — ${mixed.length} headlines, model ${MODELS.sonnet}`);
  console.log('  casing normalized: both sets lowercased before judging\n');
  console.log(`  generated shown          ${genShown}`);
  console.log(`  ...called human          ${genCalledHuman}`);
  console.log(`  MISIDENTIFICATION RATE   ${rate.toFixed(1)}%   <- record this in docs/23`);
  console.log('');
  // The control. If the judge cannot recognise real magazine headlines either, the
  // rate above is noise and says nothing about the generator.
  console.log(`  human shown              ${humanShown}`);
  console.log(`  ...correctly called human ${humanCalledHuman} (${((humanCalledHuman / humanShown) * 100).toFixed(1)}%)`);
  if (humanCalledHuman / humanShown < 0.6) {
    console.log('\n  WARNING: the judge misses real headlines too. Treat the rate as noise.');
  }
  if (passed.length) {
    console.log('\n  Generated headlines that passed as human:');
    for (const t of passed) console.log(`    - ${t}`);
  }
  console.log('');
}

main().catch((err) => { console.error(err); process.exit(1); });
