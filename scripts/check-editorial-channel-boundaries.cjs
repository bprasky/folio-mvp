#!/usr/bin/env node
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const read = p => fs.readFileSync(path.join(__dirname, '..', p), 'utf8');
const page = read('src/app/p/[slug]/page.tsx');
const channel = read('src/components/story/ProjectChannelLanding.tsx');
const hero = read('src/components/org-profile/OrgProfileHero.tsx');
const feature = read('src/app/p/[slug]/feature/page.tsx');
assert.match(page, /getPostBySlug\(params.slug\)/);
assert.match(page, /process.env.FOLIO_EDITORIAL_CHANNELS === 'true'/);
assert.match(page, /StoryRenderer post=\{post\}/);
assert.match(channel, /post\.heroAssetId/);
assert.match(channel, /featureHref/);
assert.match(feature, /StoryRenderer post=\{post\}/);
assert.match(feature, /getPostBySlug\(params.slug\)/);
assert.doesNotMatch(page, /<StoryRenderer post=\{post\} \/><\/div>/);
assert.doesNotMatch(channel, /autoplay|autoPlay|<video/i);
assert.match(hero, /process.env.NEXT_PUBLIC_FOLIO_EDITORIAL_PROFILE_HERO/);
console.log('PASS: editorial channel is gated, publication preserved, no autoplay');
